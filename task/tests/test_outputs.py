"""Verifier for the Lake Naivasha passive-sampling task.

Reads the agent's two artifacts and checks them against a frozen answer key
generated by the seeded generator shipped alongside this file (build.py,
params.py) -- so ground truth is reproducible, not asserted.

Pass rule (all must hold):
  * /app/answer.csv parses, has the required header, and carries all 57
    site x compound rows exactly once, with finite positive values;
  * at least 54 of those 57 concentrations are within 20% relative of key;
  * /app/sampling_rates.csv carries all 3 sites, each F within 10% of key.
"""
import csv, json, math, os
import pytest

KEY = json.load(open(os.path.join(os.path.dirname(__file__), "answer_key.json")))
ANSWER = "/app/answer.csv"
RATES = "/app/sampling_rates.csv"
TOL = KEY["tolerance"]


def _read(path, required):
    assert os.path.exists(path), f"{path} was not produced"
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    assert rows, f"{path} is empty"
    missing = [c for c in required if c not in (rows[0].keys() or [])]
    assert not missing, f"{path} missing column(s) {missing}; got {list(rows[0].keys())}"
    return rows


def _num(v, where):
    try:
        x = float(str(v).strip())
    except (TypeError, ValueError):
        pytest.fail(f"{where}: {v!r} is not a number")
    assert math.isfinite(x), f"{where}: {v!r} is not finite"
    return x


@pytest.fixture(scope="module")
def answers():
    rows = _read(ANSWER, ["site", "compound", "cw_ng_per_L"])
    out = {}
    for r in rows:
        k = (str(r["site"]).strip(), str(r["compound"]).strip())
        assert k not in out, f"duplicate row for {k}"
        out[k] = _num(r["cw_ng_per_L"], f"answer.csv {k}")
    return out


@pytest.fixture(scope="module")
def rates():
    rows = _read(RATES, ["site", "F"])
    return {str(r["site"]).strip(): _num(r["F"], f"sampling_rates.csv {r['site']}") for r in rows}


def test_answer_has_all_57_rows(answers):
    expected = {(s, c) for s, d in KEY["cw_ng_per_L"].items() for c in d}
    missing = sorted(expected - set(answers))
    extra = sorted(set(answers) - expected)
    assert not missing, f"missing {len(missing)} row(s), e.g. {missing[:3]}"
    assert not extra, f"unexpected row(s): {extra[:3]}"
    assert len(answers) == TOL["cw_total"]


def test_concentrations_positive(answers):
    bad = {k: v for k, v in answers.items() if v <= 0}
    assert not bad, f"non-positive concentrations: {list(bad)[:5]}"


def test_concentrations_within_tolerance(answers):
    ok, fails = 0, []
    for s, d in KEY["cw_ng_per_L"].items():
        for c, truth in d.items():
            got = answers[(s, c)]
            rel = abs(got / truth - 1.0)
            if rel <= TOL["cw_rel"]:
                ok += 1
            else:
                fails.append(f"{s}/{c}: got {got:.4g}, expected {truth:.4g} ({rel*100:.1f}% off)")
    assert ok >= TOL["cw_min_pass"], (
        f"only {ok}/{TOL['cw_total']} concentrations within {TOL['cw_rel']*100:.0f}% "
        f"(need {TOL['cw_min_pass']}). Worst: " + "; ".join(fails[:6]))


def test_sampling_rates(rates):
    missing = [s for s in KEY["F"] if s not in rates]
    assert not missing, f"sampling_rates.csv missing site(s) {missing}"
    bad = []
    for s, truth in KEY["F"].items():
        rel = abs(rates[s] / truth - 1.0)
        if rel > TOL["F_rel"]:
            bad.append(f"{s}: got {rates[s]:.4g}, expected {truth:.4g} ({rel*100:.1f}% off)")
    assert not bad, f"F outside {TOL['F_rel']*100:.0f}%: " + "; ".join(bad)
